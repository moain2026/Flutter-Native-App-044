Future<void> seedCatalog(DatabaseExecutor d) async {
  final batch = d.batch();
  for (final c in seedCategories) {
    batch.insert('categories', c);
  }
  final now = DateTime.now().toIso8601String();
  for (var i = 0; i < _p.length; i++) {
    final r = _p[i];
    batch.insert('products', {
      'id': i + 1,
      'category_id': r[0],
      'seller_id': 0,
      'name': r[1],
      'brand': r[2],
      'price': r[3],
      'old_price': r[4],
      'stock': r[5],
      'rating': r[6],
      'rating_count': r[7],
      'featured': r[8],
      'description': r[9],
      'image': 'assets/products/p${(i + 1).toString().padLeft(2, '0')}.jpg',
      'created_at': now,
    });
  }
  await batch.commit(noResult: true);
}
